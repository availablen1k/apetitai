const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const initial = storedLang() || browserLang();
    setLocale(initial);
    return initial;
  });

  const setLang = (next) => { setLocale(next); setLangState(next); };

  useEffect(() => {
    try {
      localStorage.setItem('apetit.lang', lang);
    } catch {
      /* storage blocked */
    }
    setLocale(lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(() => {
    const t = (key, params) => {
      const raw = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
      if (!params) return raw;
      return Object.entries(params).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, v), raw);
    };
    return { lang, setLang, t, toggle: () => setLang(lang === 'fi' ? 'en' : 'fi') };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useI18n must be used inside LanguageProvider');
  return ctx;
}
